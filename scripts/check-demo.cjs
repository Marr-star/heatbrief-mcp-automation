const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.join(__dirname, '..');
const lines = fs.readFileSync(path.join(root, 'docs/assets/demo.cast'), 'utf8').trim().split('\n').map(JSON.parse);
const [header, ...events] = lines;
assert.equal(header.version, 2);
assert(header.duration >= 120 && header.duration < 130);
assert(events.every((event, index) => index === 0 || event[0] >= events[index - 1][0]));
const transcript = fs.readFileSync(path.join(root, 'docs/assets/demo-transcript.txt'), 'utf8');
assert(transcript.includes('"replayed": true'));
assert(transcript.includes('timezone'));
assert(transcript.includes('[exit 2]'));
assert(transcript.includes('Mock data'));
const html = fs.readFileSync(path.join(root, 'docs/demo.html'), 'utf8');
const recording = JSON.parse(html.match(/<script id="recording" type="application\/json">([\s\S]*?)<\/script>/)[1]);
assert.equal(recording.events.length, events.length);
const elements = Object.fromEntries(['terminal','play','restart','speed','progress','time'].map(id=>[id,{textContent:'',value:'1',scrollHeight:1000,clientWidth:1000}]));
elements.recording = {textContent: JSON.stringify(recording)};
const context = vm.createContext({document:{getElementById:id=>elements[id]},requestAnimationFrame:()=>{}});
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];
vm.runInContext(script, context, {timeout:1000});
vm.runInContext('cursor=data.duration;render();',context,{timeout:1000});
assert(elements.terminal.textContent.includes('No follow-up has been sent'));
elements.restart.onclick();
assert(!elements.terminal.textContent.includes('Demo complete'));
console.log('Two-minute recording and offline playback checks passed.');
